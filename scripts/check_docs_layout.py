"""CI guard for docs/conventions/docs_and_specs.md. Offline, reads files only.

1. Every name under docs/ is lowercase snake_case: no '-', except README.md.
2. docs/specs/, docs/findings/ and docs/decisions/ files are YYYYMMDD_<slug>.md.
3. Every spec has frontmatter with a valid status; a superseded spec names an existing superseded_by;
   spec bodies carry no Status line and include Problem, Decision, Alternatives, Rollout, Verification.
4. Every decision has a valid status, a who, a kind, an existing superseded_by when superseded, and the six
   sections (Context, Decision, Why, Alternatives, Impact, Who).
5. Every docs/tech_debt/<slug>.md has valid frontmatter; open needs a bean, paid needs paid_by.
6. Every TECH_DEBT(<slug>) marker in code resolves to a tech debt file, and a paid item has none.
   Every DECISION(<slug>) marker resolves to docs/decisions/YYYYMMDD_<slug>.md.
7. Relative markdown links in docs/ resolve.
8. docs/tech_debt, docs/specs and docs/decisions README.md are generated indexes. Regenerate with --write-index.
9. Beans in .beans/ carry an A2V track (.claude/rules/a2v-track.md).

    uv run scripts/check_docs_layout.py [--write-index]
"""

from __future__ import annotations

import datetime as dt
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent

SPEC_STATUSES = {"draft", "accepted", "implemented", "superseded", "abandoned"}
DEBT_STATUSES = {"open", "accepted", "paid"}
IMPACTS = ["high", "medium", "low"]
EFFORTS = {"s", "m", "l"}
DEBT_REQUIRED = ("status", "area", "impact", "effort")

NAME_RE = re.compile(r"^[a-z0-9_.]+$")
DATED_FILE_RE = re.compile(r"^(\d{8})_[a-z0-9_]+\.md$")
SLUG_RE = re.compile(r"^[a-z0-9_]+$")
DECISION_STATUSES = {"accepted", "superseded", "reverted"}
DECISION_KINDS = {"product", "developer"}
DECISION_SECTIONS = ("Context", "Decision", "Why", "Alternatives", "Impact", "Who")
MARKER_RE = re.compile(r"TECH_DEBT\(([^)]*)\)")
DECISION_MARKER_RE = re.compile(r"DECISION\(([^)]*)\)")
LINK_RE = re.compile(r"\]\(([^)\s#]+)(?:#[^)\s]*)?\)")
MARKER_ROOTS = ("src", "tests", "scripts", "benches", "fuzz")
MARKER_SUFFIXES = {".rs", ".toml", ".yml", ".yaml", ".py", ".sh", ".md"}
MARKER_SKIP = {"check_docs_layout.py", "test_check_docs_layout.py"}
GENERATED = "Generated by `scripts/check_docs_layout.py --write-index`. Do not edit by hand.\n"
INDEX_HEADER = "# Tech debt index\n\n" + GENERATED
SPEC_SECTIONS = ("Problem", "Decision", "Alternatives", "Rollout", "Verification")
BODY_STATUS_RE = re.compile(r"^(?:\*\*)?Status(?:\*\*)?:|^#{1,6} Status\b", re.MULTILINE)
A2V_STEPS = ("Asked", "Built", "Proven", "Reviewed", "Shipped", "Verified")
WHO_RE = re.compile(r"^(Product|Developer|Reviewer|CI|Agent)\b")
OPEN_CELL_RE = re.compile(r"^(pending|n/a)\b", re.IGNORECASE)


def frontmatter(path: Path) -> dict | None:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return None
    parts = text.split("---", 2)
    if len(parts) < 3:
        return None
    data = yaml.safe_load(parts[1])
    return data if isinstance(data, dict) else None


def doc_files(folder: Path) -> list[Path]:
    if not folder.exists():
        return []
    return [p for p in sorted(folder.glob("*.md")) if p.name != "README.md"]


def title(path: Path) -> str:
    m = re.search(r"^# (.+?)\s*$", path.read_text(encoding="utf-8"), re.MULTILINE)
    return m.group(1) if m else path.stem


def valid_date(s: str) -> bool:
    try:
        dt.datetime.strptime(s, "%Y%m%d")
    except ValueError:
        return False
    return True


def check_names(root: Path, sub: str) -> list[str]:
    out = []
    base = root / sub
    if not base.exists():
        return out
    for p in sorted(base.rglob("*")):
        rel = p.relative_to(root).as_posix()
        name = p.name
        if "-" in name:
            out.append(f"{rel}: '-' in a name; use '_'")
        elif name != "README.md" and not NAME_RE.match(name):
            out.append(f"{rel}: names are lowercase snake_case")
    return out


def check_dated(docs: Path) -> list[str]:
    out = []
    for sub in ("specs", "findings", "decisions"):
        folder = docs / sub
        if not folder.exists():
            continue
        for p in sorted(folder.glob("*")):
            if p.name == "README.md":
                continue
            rel = f"docs/{sub}/{p.name}"
            m = DATED_FILE_RE.match(p.name)
            if not m or not valid_date(m.group(1)):
                out.append(f"{rel}: name must be YYYYMMDD_<slug>.md")
    return out


def check_specs(repo: Path) -> list[str]:
    out = []
    for p in doc_files(repo / "docs" / "specs"):
        rel = f"docs/specs/{p.name}"
        fm = frontmatter(p)
        if fm is None:
            out.append(f"{rel}: missing frontmatter")
            continue
        body = p.read_text(encoding="utf-8").split("---", 2)[2]
        if BODY_STATUS_RE.search(body):
            out.append(
                f"{rel}: status lives in frontmatter only; remove the Status line from the body"
            )
        headings = set(re.findall(r"^## (.+?)\s*$", body, re.MULTILINE))
        missing = [s for s in SPEC_SECTIONS if s not in headings]
        if missing:
            out.append(f"{rel}: missing sections {', '.join(missing)}")
        status = fm.get("status")
        if status not in SPEC_STATUSES:
            out.append(f"{rel}: status must be one of {sorted(SPEC_STATUSES)}")
        if status == "superseded":
            target = fm.get("superseded_by")
            if not target or not (repo / str(target)).is_file():
                out.append(f"{rel}: superseded needs superseded_by pointing at an existing file")
    return out


def debt_items(repo: Path) -> dict[str, dict]:
    items = {}
    folder = repo / "docs" / "tech_debt"
    if not folder.exists():
        return items
    for p in sorted(folder.glob("*.md")):
        if p.name != "README.md":
            items[p.stem] = frontmatter(p) or {}
    return items


def check_debt(items: dict[str, dict]) -> list[str]:
    out = []
    for slug, fm in items.items():
        rel = f"docs/tech_debt/{slug}.md"
        if not SLUG_RE.match(slug):
            out.append(f"{rel}: slug must be snake_case")
        missing = [k for k in DEBT_REQUIRED if not fm.get(k)]
        if missing:
            out.append(f"{rel}: missing {', '.join(missing)}")
            continue
        if fm["status"] not in DEBT_STATUSES:
            out.append(f"{rel}: status must be one of {sorted(DEBT_STATUSES)}")
        if fm["impact"] not in IMPACTS:
            out.append(f"{rel}: impact must be one of {IMPACTS}")
        if fm["effort"] not in EFFORTS:
            out.append(f"{rel}: effort must be one of {sorted(EFFORTS)}")
        if fm["status"] == "open" and not fm.get("bean"):
            out.append(f"{rel}: open items need a bean")
        if fm["status"] == "paid" and not fm.get("paid_by"):
            out.append(f"{rel}: paid items need paid_by")
    return out


def who_problem(who: str) -> str | None:
    if not WHO_RE.match(who):
        return "Who must start with Product:, Developer:, Reviewer:, CI or Agent:"
    if who.startswith("Agent") and not ("session " in who and "approved by" in who):
        return "an Agent Who needs its session id and 'approved by <person>'"
    return None


def check_decisions(repo: Path) -> list[str]:
    out = []
    for p in doc_files(repo / "docs" / "decisions"):
        rel = f"docs/decisions/{p.name}"
        fm = frontmatter(p)
        if fm is None:
            out.append(f"{rel}: missing frontmatter")
            continue
        if fm.get("status") not in DECISION_STATUSES:
            out.append(f"{rel}: status must be one of {sorted(DECISION_STATUSES)}")
        if not fm.get("who"):
            out.append(f"{rel}: missing who")
        elif msg := who_problem(str(fm["who"])):
            out.append(f"{rel}: {msg}")
        if fm.get("kind") not in DECISION_KINDS:
            out.append(f"{rel}: kind must be one of {sorted(DECISION_KINDS)}")
        if fm.get("status") == "superseded":
            target = fm.get("superseded_by")
            if not target or not (repo / str(target)).is_file():
                out.append(f"{rel}: superseded needs superseded_by pointing at an existing file")
        headings = set(re.findall(r"^## (.+?)\s*$", p.read_text(encoding="utf-8"), re.MULTILINE))
        missing = [s for s in DECISION_SECTIONS if s not in headings]
        if missing:
            out.append(f"{rel}: missing sections {', '.join(missing)}")
    return out


def check_links(repo: Path) -> list[str]:
    out = []
    docs = repo / "docs"
    if not docs.exists():
        return out
    for p in sorted(docs.rglob("*.md")):
        rel = p.relative_to(repo).as_posix()
        if rel.startswith("docs/templates/"):
            continue
        for target in LINK_RE.findall(p.read_text(encoding="utf-8")):
            if re.match(r"^[a-z]+:", target) or target.startswith("/"):
                continue
            resolved = (p.parent / target).resolve()
            if resolved.is_relative_to(repo.resolve()) and not resolved.exists():
                out.append(f"{rel}: broken link {target}")
    return out


def a2v_rows(text: str) -> dict[str, list[str]] | None:
    m = re.search(r"^## A2V track\s*$(.*?)(?=^## |\Z)", text, re.MULTILINE | re.DOTALL)
    if not m:
        return None
    rows = {}
    for line in m.group(1).splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 5 and cells[0] in A2V_STEPS:
            rows[cells[0]] = cells[1:5]
    return rows


def check_beans(repo: Path) -> list[str]:
    out = []
    beans_dir = repo / ".beans"
    if not beans_dir.exists():
        return out
    for p in sorted(beans_dir.rglob("*.md")):
        fm = frontmatter(p) or {}
        rel = p.relative_to(repo).as_posix()
        rows = a2v_rows(p.read_text(encoding="utf-8"))
        if rows is None:
            out.append(f"{rel}: missing '## A2V track' table (see .claude/rules/a2v-track.md)")
            continue
        missing = [s for s in A2V_STEPS if s not in rows]
        if missing:
            out.append(f"{rel}: A2V track missing steps {', '.join(missing)}")
            continue
        for step, (who, _why, _evidence, _when) in rows.items():
            if who and not OPEN_CELL_RE.match(who) and (msg := who_problem(who)):
                out.append(f"{rel}: A2V {step}: {msg}")
        asked = rows["Asked"]
        if any(not c or OPEN_CELL_RE.match(c) for c in asked[:3]):
            out.append(f"{rel}: A2V Asked needs Who, Why and Evidence")
        if fm.get("status") == "completed":
            for step in ("Built", "Proven", "Reviewed"):
                if not rows[step][2] or OPEN_CELL_RE.match(rows[step][2]):
                    out.append(f"{rel}: completed bean needs evidence for A2V {step}")
            for step in ("Shipped", "Verified"):
                ev = rows[step][2]
                if not ev or ev.lower() in ("pending", "n/a"):
                    out.append(
                        f"{rel}: A2V {step} needs evidence, 'pending: <issue>' or 'n/a: <reason>'"
                    )
    return out


def decision_slugs(repo: Path) -> set[str]:
    folder = repo / "docs" / "decisions"
    if not folder.exists():
        return set()
    return {p.stem[9:] for p in folder.glob("*.md") if DATED_FILE_RE.match(p.name)}


def markers(repo: Path, pattern: re.Pattern = MARKER_RE) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for sub in MARKER_ROOTS:
        base = repo / sub
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file() or p.suffix not in MARKER_SUFFIXES or p.name in MARKER_SKIP:
                continue
            for i, line in enumerate(
                p.read_text(encoding="utf-8", errors="replace").splitlines(), 1
            ):
                for slug in pattern.findall(line):
                    found.setdefault(slug, []).append(f"{p.relative_to(repo).as_posix()}:{i}")
    return found


def check_decision_markers(slugs: set[str], found: dict[str, list[str]]) -> list[str]:
    return [
        f"{where[0]}: DECISION({slug}) has no docs/decisions/YYYYMMDD_{slug}.md"
        for slug, where in sorted(found.items())
        if slug not in slugs
    ]


def check_markers(items: dict[str, dict], found: dict[str, list[str]]) -> list[str]:
    out = []
    for slug, where in sorted(found.items()):
        if slug not in items:
            out.append(f"{where[0]}: TECH_DEBT({slug}) has no docs/tech_debt/{slug}.md")
        elif items[slug].get("status") == "paid":
            out.append(f"{where[0]}: TECH_DEBT({slug}) is paid; remove the marker")
    return out


def render_index(items: dict[str, dict]) -> str:
    order = {s: i for i, s in enumerate(["open", "accepted", "paid"])}
    rows = sorted(
        items.items(),
        key=lambda kv: (
            order.get(kv[1].get("status"), 9),
            IMPACTS.index(kv[1]["impact"]) if kv[1].get("impact") in IMPACTS else 9,
            kv[0],
        ),
    )
    lines = [
        INDEX_HEADER,
        "| Item | Status | Impact | Effort | Area | Bean |",
        "|---|---|---|---|---|---|",
    ]
    for slug, fm in rows:
        lines.append(
            f"| [{slug}]({slug}.md) | {fm.get('status', '')} | {fm.get('impact', '')} | "
            f"{fm.get('effort', '')} | {fm.get('area', '')} | {fm.get('bean', '')} |"
        )
    return "\n".join(lines) + "\n"


def render_dated_index(repo: Path, sub: str, heading: str) -> str:
    lines = [f"# {heading}\n\n" + GENERATED, "| Date | Title | Status |", "|---|---|---|"]
    for p in reversed(doc_files(repo / "docs" / sub)):
        fm = frontmatter(p) or {}
        d = p.name[:8]
        lines.append(
            f"| {d[:4]}-{d[4:6]}-{d[6:]} | [{title(p)}]({p.name}) | {fm.get('status', '')} |"
        )
    return "\n".join(lines) + "\n"


def indexes(repo: Path) -> dict[str, str | None]:
    items = debt_items(repo)
    out: dict[str, str | None] = {"tech_debt": render_index(items) if items else None}
    for sub, heading in (("specs", "Spec index"), ("decisions", "Decision index")):
        out[sub] = (
            render_dated_index(repo, sub, heading) if doc_files(repo / "docs" / sub) else None
        )
    return out


def check_index(repo: Path) -> list[str]:
    out = []
    for sub, expected in indexes(repo).items():
        index = repo / "docs" / sub / "README.md"
        if expected is None and not index.exists():
            continue
        if not index.exists() or index.read_text(encoding="utf-8") != expected:
            out.append(
                f"docs/{sub}/README.md: stale; run scripts/check_docs_layout.py --write-index"
            )
    return out


def write_indexes(repo: Path) -> None:
    for sub, expected in indexes(repo).items():
        if expected is not None:
            folder = repo / "docs" / sub
            folder.mkdir(parents=True, exist_ok=True)
            (folder / "README.md").write_text(expected, encoding="utf-8", newline="\n")


def problems(repo: Path = REPO) -> list[str]:
    items = debt_items(repo)
    return [
        *check_names(repo, "docs"),
        *check_dated(repo / "docs"),
        *check_specs(repo),
        *check_decisions(repo),
        *check_links(repo),
        *check_beans(repo),
        *check_decision_markers(decision_slugs(repo), markers(repo, DECISION_MARKER_RE)),
        *check_debt(items),
        *check_markers(items, markers(repo)),
        *check_index(repo),
    ]


def main(argv: list[str]) -> int:
    if "--write-index" in argv:
        write_indexes(REPO)
    found = problems()
    for p in found:
        print(p)
    if found:
        print(f"\n{len(found)} docs layout problem(s). See docs/conventions/docs_and_specs.md.")
        return 1
    print("docs layout OK")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
