"""Generate tests/data/bigquery_golden.tsv from BigQuery HLL_COUNT over synthetic inputs.

Every input is generated in the query (GENERATE_ARRAY, string literals); no table is read, so
the fixtures contain no real data. Re-run to refresh after a BigQuery change:

    uv run scripts/gen_bigquery_fixtures.py --project <billing-project>

Rows (tab separated, base64 sketches):

    INIT   <name> <b64 sketch>                     <HLL_COUNT.EXTRACT>
    MERGE  <name> <b64 input>... <b64 MERGE_PARTIAL> <HLL_COUNT.MERGE>

A MERGE row lists its inputs in a fixed order; the expected result does not depend on order.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from google.cloud import bigquery

OUT = Path(__file__).resolve().parent.parent / "tests" / "data" / "bigquery_golden.tsv"

# Cardinalities cover empty-ish, sparse, the sparse -> dense crossover at p=15 (about 4.6k
# distinct values) and dense up to 10^6.
CARDINALITIES = [1, 2, 10, 100, 1000, 3000, 5000, 6000, 20000, 100000, 1000000]
PRECISIONS = [10, 15]

VALUE = {
    "INT64": "x",
    "STRING": "CONCAT('v', CAST(x AS STRING))",
    "BYTES": "CAST(CONCAT('b', CAST(x AS STRING)) AS BYTES)",
}

INIT_SQL = """
SELECT n, TO_BASE64(s) b64, HLL_COUNT.EXTRACT(s) est
FROM (
  SELECT n, HLL_COUNT.INIT({value}, {p}) s
  FROM UNNEST(@ns) n, UNNEST(GENERATE_ARRAY(0, n - 1)) x
  GROUP BY n
)
ORDER BY n
"""

# Each case: (name, list of (precision, lo, hi, kind)) -> sketches over x in [lo, hi).
MERGE_CASES = [
    ("int_sparse_sparse_overlap_p15", [(15, 0, 100), (15, 50, 150)]),
    ("int_sparse_sparse_to_dense_p15", [(15, 0, 3000), (15, 3000, 6000)]),
    ("int_sparse_dense_p15", [(15, 0, 500), (15, 1000, 40000)]),
    ("int_dense_sparse_p15", [(15, 1000, 40000), (15, 0, 500)]),
    ("int_dense_dense_p15", [(15, 0, 50000), (15, 25000, 90000)]),
    ("int_lowering_sparse_p15_p10", [(15, 0, 200), (10, 100, 300)]),
    ("int_lowering_dense_p15_p10", [(15, 0, 50000), (10, 0, 20000)]),
    ("int_lowering_sparse_dense_p10_p15", [(10, 0, 100), (15, 0, 60000)]),
    ("int_ten_way_disjoint_p15", [(15, i * 700, (i + 1) * 700) for i in range(10)]),
    ("int_duplicates_p15", [(15, 0, 1000), (15, 0, 1000), (15, 0, 1000)]),
]


def run(client: bigquery.Client, sql: str, params: list | None = None) -> list[bigquery.Row]:
    cfg = bigquery.QueryJobConfig(query_parameters=params or [])
    return list(client.query(sql, job_config=cfg).result())


def merge_sql(kind: str, parts: list[tuple[int, int, int]]) -> str:
    value = VALUE[kind]
    inits = " UNION ALL ".join(
        f"SELECT {i} i, (SELECT HLL_COUNT.INIT({value}, {p}) "
        f"FROM UNNEST(GENERATE_ARRAY({lo}, {hi - 1})) x) s"
        for i, (p, lo, hi) in enumerate(parts)
    )
    return f"""
WITH parts AS ({inits})
SELECT
  (SELECT ARRAY_AGG(TO_BASE64(s) ORDER BY i) FROM parts) inputs,
  (SELECT TO_BASE64(HLL_COUNT.MERGE_PARTIAL(s)) FROM parts) merged,
  (SELECT HLL_COUNT.MERGE(s) FROM parts) est
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True, help="billing project for the query jobs")
    args = ap.parse_args()
    client = bigquery.Client(project=args.project)

    lines = [
        "# Generated by scripts/gen_bigquery_fixtures.py from BigQuery HLL_COUNT over synthetic",
        "# inputs (GENERATE_ARRAY). Do not edit by hand.",
    ]
    ns = bigquery.ArrayQueryParameter("ns", "INT64", CARDINALITIES)
    for kind, value in VALUE.items():
        for p in PRECISIONS:
            for row in run(client, INIT_SQL.format(value=value, p=p), [ns]):
                lines.append(f"INIT\t{kind.lower()}_p{p}_n{row.n}\t{row.b64}\t{row.est}")
    for name, parts in MERGE_CASES:
        row = run(client, merge_sql("INT64", parts))[0]
        lines.append("\t".join(["MERGE", name, *row.inputs, row.merged, str(row.est)]))
    for name, parts in MERGE_CASES[:3]:
        row = run(client, merge_sql("STRING", parts))[0]
        name = name.replace("int_", "string_")
        lines.append("\t".join(["MERGE", name, *row.inputs, row.merged, str(row.est)]))

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 2} rows to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
