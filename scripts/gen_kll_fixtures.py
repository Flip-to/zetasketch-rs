"""Generate tests/data/kll_golden.tsv from BigQuery KLL_QUANTILES over synthetic inputs.

    uv run --group bigquery python scripts/gen_kll_fixtures.py --project <billing-project>

Two steps per sketch, because KLL_QUANTILES.INIT is randomized per execution:
1. build the sketch with INIT_INT64 / INIT_FLOAT64 and store its bytes;
2. in a separate query, run EXTRACT_* and EXTRACT_POINT_* on FROM_BASE64(<stored bytes>), so the
   expected outputs belong to exactly the stored sketch.

Rows (tab separated):

    KLL  <family>_k<k>_n<n>  <INT64|FLOAT64>  <b64 sketch>  <q2>  <q4>  <q10>  <q100>  <points>

Quantile vectors are comma separated; <points> is `phi=value` pairs separated by commas.
No table is read; every input comes from GENERATE_ARRAY.
"""

from __future__ import annotations

import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "data" / "kll_golden.tsv"

FAMILIES = {
    "seq": ("INT64", "x"),
    "neg": ("INT64", "-x * 7919 - 1"),
    "dup": ("INT64", "MOD(x, 17) - 8"),
    "big": ("INT64", "x * 92233720368547"),
    "f64": ("FLOAT64", "CAST(x AS FLOAT64) * 0.5 - 100.25"),
    "f64tiny": ("FLOAT64", "CAST(x AS FLOAT64) * 1e-300"),
}
KS = [10, 100, 1000]
NS = [1, 2, 10, 100, 1000, 10000, 100000]
QS = [2, 4, 10, 100]
PHIS = [0.0, 0.001, 0.1, 0.25, 0.5, 0.75, 0.9, 0.999, 1.0]


def fmt(v) -> str:
    return repr(float(v)) if isinstance(v, float) else str(v)


def main() -> int:
    from google.cloud import bigquery

    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    args = ap.parse_args()
    client = bigquery.Client(project=args.project)

    lines = [
        "# Generated by scripts/gen_kll_fixtures.py from BigQuery KLL_QUANTILES over synthetic",
        "# inputs (GENERATE_ARRAY). Do not edit by hand.",
    ]
    for fam, (typ, expr) in FAMILIES.items():
        for k in KS:
            init = f"""
SELECT n, TO_BASE64(KLL_QUANTILES.INIT_{typ}({expr}, {k})) AS b64
FROM UNNEST(@ns) AS n, UNNEST(GENERATE_ARRAY(1, n)) AS x
GROUP BY n ORDER BY n"""
            cfg = bigquery.QueryJobConfig(
                query_parameters=[bigquery.ArrayQueryParameter("ns", "INT64", NS)]
            )
            stored = [(r.n, r.b64) for r in client.query(init, job_config=cfg).result()]
            for n, b64 in stored:
                qs = ", ".join(f"KLL_QUANTILES.EXTRACT_{typ}(s, {q}) AS q{q}" for q in QS)
                pts = ", ".join(
                    f"KLL_QUANTILES.EXTRACT_POINT_{typ}(s, {p}) AS p{i}" for i, p in enumerate(PHIS)
                )
                extract = f"SELECT {qs}, {pts} FROM (SELECT FROM_BASE64(@b) AS s)"
                cfg = bigquery.QueryJobConfig(
                    query_parameters=[bigquery.ScalarQueryParameter("b", "STRING", b64)]
                )
                r = next(iter(client.query(extract, job_config=cfg).result()))
                cols = [",".join(fmt(v) for v in r[f"q{q}"]) for q in QS]
                points = ",".join(f"{p}={fmt(r[f'p{i}'])}" for i, p in enumerate(PHIS))
                lines.append("\t".join(["KLL", f"{fam}_k{k}_n{n}", typ, b64, *cols, points]))
                print(fam, k, n, flush=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(lines) - 2} rows to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
