"""Generate src/bias_data.rs from ZetaSketch Java `Data.java` (Apache-2.0).

    python scripts/gen_bias_data.py <path/to/zetasketch/java/.../hllplus/Data.java>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "bias_data.rs"


def rows(src: str, name: str) -> list[list[str]]:
    start = src.index("{", src.index(name + " = {"))
    depth, row, out = 0, 0, []
    for i in range(start, len(src)):
        c = src[i]
        if c == "{":
            depth += 1
            row = i
        elif c == "}":
            depth -= 1
            if depth == 1:
                body = re.sub(r"//[^\n]*", "", src[row + 1 : i])
                out.append([v.strip() for v in body.split(",") if v.strip()])
            if depth == 0:
                return out
    raise ValueError(f"unterminated {name}")


def literal(v: str) -> str:
    return v if any(c in v for c in ".eE") else v + ".0"


def main(argv: list[str]) -> int:
    src = Path(argv[1]).read_text(encoding="utf-8")
    lines = [
        "// Generated by scripts/gen_bias_data.py from ZetaSketch Java `Data.java` (Apache-2.0).",
        "// Do not edit by hand.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::excessive_precision)]",
        "",
    ]
    for java, rust in (("meanData", "MEAN_DATA"), ("biasData", "BIAS_DATA")):
        data = rows(src, java)
        lines.append(f"pub(crate) static {rust}: [&[f64]; {len(data)}] = [")
        for p, nums in enumerate(data, start=4):
            lines.append(f"    // precision {p}")
            lines.append("    &[")
            nums = [literal(n) for n in nums]
            for i in range(0, len(nums), 6):
                lines.append("        " + ", ".join(nums[i : i + 6]) + ",")
            lines.append("    ],")
        lines.append("];")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
